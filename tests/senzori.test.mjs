// Teste „Mod senzori” (orientare telefon) și comutarea rapidă a modului roșu — Bolta 2.1.0.
// Rulare: node tests/senzori.test.mjs   (Playwright + Chromium; PW_ROOT / CHROMIUM_PATH opționale; rețea blocată)
import {createRequire} from 'module';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
const require = createRequire(process.env.PW_ROOT || import.meta.url);
const {chromium} = require('playwright');
const HERE = path.dirname(fileURLToPath(import.meta.url));
const APP = pathToFileURL(path.resolve(HERE, '..', 'index.html')).href;
let pass = 0, fail = 0;
const ok = (c, n, i) => { if (c) { pass++; console.log('  ok   ' + n); } else { fail++; console.log('  FAIL ' + n + (i === undefined ? '' : ' ' + JSON.stringify(i).slice(0, 300))); } };
const near = (a, b, tol = 0.2) => Math.abs(a - b) <= tol;
const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox']});
const ctx = await browser.newContext({viewport: {width: 420, height: 800}, locale: 'ro-RO'});
const net = [], errs = [];
await ctx.route(/^https?:/, r => { net.push(r.request().url()); r.abort(); });
const page = await ctx.newPage();
page.on('pageerror', e => errs.push(e.message));
page.on('console', m => { if (/Content Security Policy|Refused to/i.test(m.text())) errs.push(m.text()); });
await page.goto(APP);
await page.waitForFunction(() => window.__bolta && window.__bolta.FR.ok);
console.log('Bolta — mod senzori');
const f = (al, be, ga) => page.evaluate(a => { const b = window.__bolta, v = b.dirToView(b.orientToDir(...a)); return [v.A, v.a]; }, [al, be, ga]);
let v = await f(0, 90, 0); ok(near(v[0], 0) && near(v[1], 0), 'telefon vertical spre nord → A=0°, h=0°', v);
v = await f(90, 90, 0); ok(near(v[0], 270) && near(v[1], 0), 'alpha=90° (rotit la stânga) → vest (A=270°)', v);
v = await f(270, 90, 0); ok(near(v[0], 90) && near(v[1], 0), 'alpha=270° → est (A=90°)', v);
v = await f(180, 90, 0); ok(near(v[0], 180) && near(v[1], 0), 'alpha=180° → sud', v);
v = await f(0, 135, 0); ok(near(v[1], 45), 'beta=135° → înălțime 45°', v);
v = await f(0, 180, 0); ok(near(v[1], 90), 'beta=180° (ecran în jos) → zenit', v);
v = await f(0, 0, 0); ok(near(v[1], -90), 'telefon culcat cu ecranul în sus → nadir', v);
await page.click('#btnSensor');
ok((await page.getAttribute('#btnSensor', 'aria-pressed')) === 'true', 'butonul 📱 pornit (aria-pressed)');
await page.evaluate(() => { const e = new DeviceOrientationEvent('deviceorientationabsolute', {alpha: 90, beta: 100, gamma: 0, absolute: true}); for (let i = 0; i < 30; i++) window.dispatchEvent(e); });
await page.waitForTimeout(400);
const st = await page.evaluate(() => ({A: window.__bolta.V.A, a: window.__bolta.V.a, full: window.__bolta.S.opts.full}));
ok(near(st.A, 270, 0.5) && near(st.a, 10, 0.5) && st.full === false, 'cerul urmărește evenimentele de orientare (A=270°, h=10°, fără „tot cerul”)', st);
await page.click('#btnSensor');
const off = await page.evaluate(() => ({on: window.__bolta.SEN.on, full: window.__bolta.S.opts.full, A: window.__bolta.V.A}));
ok(off.on === false && off.full === true && near(off.A, 180, 0.5), 'oprirea restaurează vederea anterioară', off);
await page.click('#btnRedQ');
ok((await page.evaluate(() => document.documentElement.getAttribute('data-theme'))) === 'red', 'butonul 🔴 → tema roșie');
await page.click('#btnRedQ');
ok((await page.evaluate(() => document.documentElement.getAttribute('data-theme'))) !== 'red', 'al doilea clic restaurează tema anterioară');
await page.click('#btnSensor'); await page.waitForTimeout(2900);
ok(await page.evaluate(() => window.__bolta.SEN.on === false), 'fără senzori (evenimente absente) → se oprește singur după 2,5 s');
ok(net.length === 0, 'nicio cerere în rețea', net);
ok(errs.length === 0, 'fără erori JS/CSP', errs);
await browser.close();
console.log(pass + ' ok, ' + fail + ' eșuate');
process.exit(fail ? 1 : 0);
